#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-2.0-or-later
#
# Install the CDJ-2000NXS2 machine model into a QEMU source tree.
#
#   usage: ./install_machine.sh [path-to-qemu-tree]     (default: ~/qemu)
#
# Idempotent. Everything goes into hw/sh4/cdj/, which this script owns (stale
# files there are removed); hw/sh4/meson.build gains one line, subdir('cdj').
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
Q="${1:-$HOME/qemu}"
D="$Q/hw/sh4/cdj"

if [ ! -d "$Q/hw/sh4" ]; then
    echo "error: '$Q' does not look like a QEMU tree (no hw/sh4)." >&2
    echo "clone it first:" >&2
    echo "  git clone --depth 1 --branch v9.1.0 https://gitlab.com/qemu-project/qemu.git ~/qemu" >&2
    exit 1
fi

# Copy one file, dropping CRLF: a Windows checkout must build the same bytes.
# Written only when the content changed: a fresh mtime on a meson.build forces
# a reconfigure, and on a source a recompile. Every path written is recorded,
# so anything else left in hw/sh4/cdj/ can be removed as stale at the end.
INSTALLED=()
put_file() {   # <temp file with the final content> <tree file>
    mkdir -p "$(dirname "$2")"
    if cmp -s "$1" "$2"; then rm -f "$1"; else mv "$1" "$2"; fi
    INSTALLED+=("$2")
}
install_src() {   # <project file> <tree file>
    local t
    t="$(mktemp)"
    sed 's/\r$//' "$1" > "$t"
    put_file "$t" "$2"
}

# --- the old flat layout -----------------------------------------------------
# Removed so a stale hw/sh4/cdj2000nxs2.c cannot be mistaken for the built one.
rm -rf "$Q/hw/sh4/c6x"
rm -f "$Q/hw/sh4/cdj2000nxs2.c" "$Q/hw/sh4/sh7269gui.c" \
      "$Q/hw/sh4/cdj_panelkeys.h" "$Q/hw/sh4/minimp3.h"

# --- board sources ----------------------------------------------------------
mkdir -p "$D"
# The whole hw/cdj/ tree is installed; hw/cdj/meson.build lists what is built.
while IFS= read -r f; do
    install_src "$f" "$D/${f#$HERE/../../hw/cdj/}"
done < <(find "$HERE/../../hw/cdj" -path "$HERE/../../hw/cdj/c6x" -prune -o -type f \( -name '*.[ch]' -o -name meson.build \) -print | sort)
echo "installed hw/sh4/cdj/ (board sources)"

# The TMS320C6655 DSP: the C66x core and the SoC models. The offline tools
# (runner, tests, image loader) stay out of the machine. It sits under cdj/ so
# the board's '#include "c6x/c66x.h"' resolves.
C6X_FILES=(c66x.h c66x_core.c c66x_core_int.h c66x_decode.c c66x_decode.h c66x_ext_table.h)
C6X_SRCS=(c66x_core.c c66x_decode.c)
for f in "$HERE"/../../hw/cdj/c6x/soc_*.[ch]; do
    C6X_FILES+=("${f#$HERE/../../hw/cdj/c6x/}")
    case "$f" in *.c) C6X_SRCS+=("${f#$HERE/../../hw/cdj/c6x/}") ;; esac
done
for f in "$HERE"/../../hw/cdj/c6x/binutils/*.h; do
    C6X_FILES+=("${f#$HERE/../../hw/cdj/c6x/}")
done
for f in "${C6X_FILES[@]}"; do
    install_src "$HERE/../../hw/cdj/c6x/$f" "$D/c6x/$f"
done
echo "installed hw/sh4/cdj/c6x/ (${#C6X_FILES[@]} files)"

# The DSP core is its own static library because its float results must be
# IEEE-exact per operation (-ffp-contract=off). Its meson.build is generated
# into the tree only, never into a patch, because it carries host paths: the
# JIT tools dir and library dir are baked in as C strings and used by native
# programs at run time, so on MSYS2 they go through cygpath -m.
nativepath() {
    if command -v cygpath >/dev/null 2>&1; then cygpath -m "$1"; else printf '%s' "$1"; fi
}
JIT_TOOLS="$(nativepath "$HERE/../../hw/cdj/c6x/tools")"
JIT_LIBDIR="$(nativepath "${C66X_JIT_LIBDIR:-$HOME/build/c6x}")"
C6X_MESON="$(mktemp)"
{
    echo "# GENERATED by scripts/build/install_machine.sh -- host paths; never commit or patch this"
    echo "cdjc6x = static_library('cdjc6x', files("
    for f in "${C6X_SRCS[@]}"; do echo "  '$f',"; done
    # -march=native is bit-exact and a few percent faster. C66X_JIT_AUTO runs
    # the generator from this tree against the offline core library
    # (make -C hw/cdj/c6x O=~/build/c6x ~/build/c6x/libc66x.so).
    echo "), c_args: ['-O3', '-march=native', '-ffp-contract=off', '-frounding-math', '-Wno-error',"
    echo "           '-DC66X_JIT_TOOLS=\"$JIT_TOOLS\"', '-DC66X_JIT_LIBDIR=\"$JIT_LIBDIR\"'],"
    echo "   build_by_default: false)"
    echo "sh4_ss.add(when: 'CONFIG_CDJ2000NXS2',"
    echo "           if_true: declare_dependency(link_whole: cdjc6x))"
} > "$C6X_MESON"
put_file "$C6X_MESON" "$D/c6x/meson.build"
echo "hw/sh4/cdj/c6x/meson.build: ${#C6X_SRCS[@]} sources"

# Anything in hw/sh4/cdj/ this run did not write is stale (a file deleted from
# the project, an old split output): remove it so it cannot be built or read.
while IFS= read -r f; do
    printf '%s\n' "${INSTALLED[@]}" | grep -qxF "$f" || { rm -f "$f"; echo "removed stale ${f#$Q/}"; }
done < <(find "$D" -type f)

# --- hw/sh4/meson.build -----------------------------------------------------
# Strip every earlier form (the two flat board lines, the marked c6x block and
# its unmarked first cut) and leave one subdir('cdj'). Rewritten only on a
# real change: touching meson.build forces a reconfigure.
SH4_MESON="$(mktemp)"
sed -e "/^sh4_ss.add(when: 'CONFIG_CDJ2000NXS2', if_true: files('cdj2000nxs2.c'))$/d" \
    -e "/^sh4_ss.add(when: 'CONFIG_SH7269GUI', if_true: files('sh7269gui.c'))$/d" \
    -e '/^# cdjc6x begin/,/^# cdjc6x end/d' \
    -e '/^cdjc6x = static_library/,/link_whole: cdjc6x))/d' \
    -e "/^subdir('cdj')$/d" \
    "$Q/hw/sh4/meson.build" > "$SH4_MESON"
echo "subdir('cdj')" >> "$SH4_MESON"
if cmp -s "$SH4_MESON" "$Q/hw/sh4/meson.build"; then
    echo "hw/sh4/meson.build unchanged"
else
    cat "$SH4_MESON" > "$Q/hw/sh4/meson.build"
    echo "wrote hw/sh4/meson.build (subdir('cdj'))"
fi
rm -f "$SH4_MESON"

# --- Kconfig --------------------------------------------------------------
# sh_serial.c is built by CONFIG_SH_SCI; there is no SH_SERIAL symbol.
if grep -q CDJ2000NXS2 "$Q/hw/sh4/Kconfig"; then
    echo "Kconfig already patched"
else
    cat >> "$Q/hw/sh4/Kconfig" <<'EOF'

config CDJ2000NXS2
    bool
    default y
    depends on SH4
    select SH_SCI
    select UNIMP
    select PFLASH_CFI02
EOF
    echo "patched hw/sh4/Kconfig"
fi

echo
echo "next:"
echo "  cd $Q && ./configure --target-list=sh4-softmmu --disable-werror"
echo "  ninja -C build qemu-system-sh4"
